export function normalizeLanguage(raw: string | null | undefined): SupportedLanguage {
	const base = String(raw ?? '').trim().toLowerCase().split('-')[0] ?? '';
	return LANGUAGE_SET.has(base) ? (base as SupportedLanguage) : 'en';
}

export function translate(
	language: SupportedLanguage,
	key: I18nKey,
	vars?: Record<string, string | number>
) {
	const template = I18N[language][key] ?? I18N_EN[key];
	if (!vars) return template;
	return template.replace(/\{(\w+)\}/g, (_match, name: string) => String(vars[name] ?? ''));
}
