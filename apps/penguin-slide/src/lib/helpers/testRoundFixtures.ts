export function buildSimulatedLossEvents(stakeAmount: number) {
	const startValue = Math.round(stakeAmount * 100);
	return [
		{
			stepIndex: 0,
			landedStep: 'LEFT',
			steps: {
				LEFT: { item: 'BANANA', sinking: true },
				RIGHT: { item: 'NOTHING', sinking: false },
			},
			accumulatedWinAmount: 0,
			winAmount: -startValue,
			lifeVests: 0,
			success: false,
			applies: true,
			terminal: true,
		},
		{
			type: 'finish',
			totalSteps: 1,
			totalWinAmount: 0,
			betAmount: startValue,
			multiplier: 0,
			success: false,
		},
	];
}

export function buildSimulatedLossBetId(stakeAmount: number) {
	return `simulated-loss-${Math.round(stakeAmount * 100)}`;
}
